/**
 * Demo data seeded on first launch. Dates are relative to "today" so the
 * dashboard (upcoming interviews, timeline) always looks alive.
 * Company names are fictional.
 */
const ts = (daysAgo: number, hour = 9) => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
};

